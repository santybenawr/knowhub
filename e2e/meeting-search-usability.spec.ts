import { expect, test } from '@playwright/test'
import { completeOnboarding, OMEGA_TRANSCRIPT, signupAndOnboard } from './helpers'

test('failed transcript import retries the same meeting and refreshes the completed analysis without reload', async ({ page }) => {
  await signupAndOnboard(page, 'Importador')
  await completeOnboarding(page, 'Reintentos')
  await page.goto('/meetings/new')
  await page.getByRole('button', { name: /Importar transcripción/ }).click()
  await page.getByLabel('Título', { exact: true }).fill('Reunión sin duplicados')
  await page.getByLabel('Transcripción', { exact: true }).fill('00:00 Ana:')
  await page.getByRole('button', { name: 'Importar y analizar' }).click()
  await expect(page.getByRole('alert').filter({ hasText: 'No pudimos leer segmentos' })).toBeVisible()
  await expect(page.getByText('La reunión ya está creada.', { exact: false })).toBeVisible()
  await page.getByLabel('Transcripción', { exact: true }).fill(OMEGA_TRANSCRIPT)
  await page.getByRole('button', { name: 'Importar y analizar' }).click()
  await expect(page).toHaveURL(/\/meetings\/[0-9a-f-]{36}/)
  await page.getByRole('tab', { name: /Decisiones/ }).click()
  await expect(page.getByText(/Entonces vamos a seleccionar el proveedor B/)).toBeVisible({ timeout: 30_000 })

  await page.getByRole('button', { name: /Fuente/ }).first().click()
  await expect(page.getByRole('tab', { name: 'Transcripción' })).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByLabel('Desplazar al fragmento seleccionado')).toBeVisible()
  await page.getByRole('button', { name: 'Santiago', exact: true }).click()
  await page.getByLabel('Nombre para Santiago').fill('Santiago revisado')
  await page.getByRole('button', { name: 'Guardar', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Santiago revisado', exact: true })).toBeVisible()
  await page.goto('/meetings')
  await expect(page.getByRole('link', { name: /Reunión sin duplicados/ })).toHaveCount(1)
})

test('stored conversations reopen with citations and preserve follow-up answers after a reload', async ({ page, browser }) => {
  await signupAndOnboard(page, 'Historial')
  await completeOnboarding(page, 'Conversaciones')
  await page.goto('/meetings/new')
  await page.getByRole('button', { name: /Importar transcripción/ }).click()
  await page.getByLabel('Título', { exact: true }).fill('Fuentes del historial')
  await page.getByLabel('Transcripción', { exact: true }).fill(OMEGA_TRANSCRIPT)
  await page.getByRole('button', { name: 'Importar y analizar' }).click()
  await expect(page).toHaveURL(/\/meetings\/[0-9a-f-]{36}/)
  const meetingId = page.url().split('/').at(-1)!
  await expect.poll(async () => {
    const response = await page.request.get(`/api/meetings/${meetingId}/status`)
    return (await response.json()).embeddingStatus
  }).toBe('completed')
  await page.goto('/ask')
  await page.getByLabel('Tu pregunta').fill('¿Qué proveedor seleccionamos?')
  await page.getByRole('button', { name: 'Preguntar', exact: true }).click()
  await expect(page.getByText('Fuentes', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Abrir conversación guardada' }).click()
  await expect(page).toHaveURL(/\/ask\/[0-9a-f-]{36}/)
  const historyUrl = page.url()
  await expect(page.getByRole('link', { name: /Ver fuente 1/ }).first()).toBeVisible()
  await page.getByLabel('Tu pregunta').fill('¿Quién contacta al proveedor?')
  const followUp = page.waitForResponse(response => response.url().endsWith('/api/ask') && response.request().method() === 'POST')
  await page.getByRole('button', { name: 'Preguntar', exact: true }).click()
  expect((await followUp).status()).toBe(200)
  await expect(page.getByText('Fuentes', { exact: true })).toHaveCount(2)
  // A terminal frame cancels the reader; wait for the composer, not network EOF.
  await page.getByLabel('Tu pregunta').fill('¿Cuál es el siguiente paso?')
  await expect(page.getByRole('button', { name: 'Preguntar', exact: true })).toBeEnabled()
  await page.reload()
  await expect(page.getByText('¿Quién contacta al proveedor?', { exact: true })).toBeVisible()
  await expect(page.getByText('Fuentes', { exact: true })).toHaveCount(2)
  await page.getByRole('link', { name: 'Volver a preguntas y conversaciones' }).click()
  await page.getByRole('link', { name: '¿Qué proveedor seleccionamos?', exact: true }).click()
  await expect(page).toHaveURL(historyUrl)

  const context = await browser.newContext()
  const other = await context.newPage()
  await signupAndOnboard(other, 'Otrohistorial')
  await completeOnboarding(other, 'Privacidad')
  await other.goto(historyUrl)
  await expect(other.getByText('No encontramos esta página')).toBeVisible()
  await context.close()
})

test('search restores URL filters on back navigation and Ask preserves questions too short to send', async ({ page }) => {
  await signupAndOnboard(page, 'Filtros')
  await completeOnboarding(page, 'Búsqueda')
  await page.goto('/search?q=primera')
  await page.getByLabel('Búsqueda', { exact: true }).fill('segunda')
  await page.getByLabel('Tipo de recurso').selectOption('meeting')
  await page.getByRole('button', { name: 'Buscar', exact: true }).click()
  await expect(page).toHaveURL(/q=segunda&kind=meeting/)
  await page.goBack()
  await expect(page.getByLabel('Búsqueda', { exact: true })).toHaveValue('primera')
  await expect(page.getByLabel('Tipo de recurso')).toHaveValue('')
  await page.goto('/search?q=uno&q=dos')
  await expect(page.getByLabel('Búsqueda', { exact: true })).toHaveValue('uno')
  await page.goto('/search?project=invalid&q=hola')
  await expect(page.getByText('No encontramos esta página')).toBeVisible()
  await page.goto('/ask')
  await page.getByLabel('Tu pregunta').fill('a')
  await expect(page.getByRole('button', { name: 'Preguntar', exact: true })).toBeDisabled()
  await page.getByLabel('Tu pregunta').press('Enter')
  await expect(page.getByLabel('Tu pregunta')).toHaveValue('a')
})
